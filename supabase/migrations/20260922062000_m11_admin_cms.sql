begin;

create table if not exists public.site_settings (
  key text primary key,
  group_name text not null default 'general',
  label text not null,
  value jsonb not null default 'null'::jsonb,
  is_public boolean not null default true,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint site_settings_key_format check (key ~ '^[a-z0-9]+(?:[._-][a-z0-9]+)*$'),
  constraint site_settings_label_length check (char_length(label) between 2 and 120)
);

create table if not exists public.content_sections (
  id uuid primary key default gen_random_uuid(),
  section_key text not null unique,
  eyebrow text,
  title text not null,
  body text not null default '',
  cta_label text,
  cta_href text,
  metadata jsonb not null default '{}'::jsonb,
  status public.content_status not null default 'draft',
  sort_order integer not null default 100,
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  published_at timestamptz,
  archived_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint content_sections_key_format check (section_key ~ '^[a-z0-9]+(?:[._-][a-z0-9]+)*$'),
  constraint content_sections_title_length check (char_length(title) between 2 and 220),
  constraint content_sections_body_length check (char_length(body) <= 12000)
);

create table if not exists public.testimonials (
  id uuid primary key default gen_random_uuid(),
  client_name text not null,
  company_name text,
  role_title text,
  quote text not null,
  permission_granted boolean not null default false,
  case_study_id uuid references public.case_studies(id) on delete set null,
  media_asset_id uuid references public.media_assets(id) on delete set null,
  status public.content_status not null default 'draft',
  sort_order integer not null default 100,
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  published_at timestamptz,
  archived_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint testimonials_name_length check (char_length(client_name) between 2 and 160),
  constraint testimonials_quote_length check (char_length(quote) between 10 and 4000)
);

create table if not exists public.faqs (
  id uuid primary key default gen_random_uuid(),
  category text not null default 'general',
  question text not null,
  answer text not null,
  status public.content_status not null default 'draft',
  sort_order integer not null default 100,
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  published_at timestamptz,
  archived_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint faqs_question_length check (char_length(question) between 4 and 280),
  constraint faqs_answer_length check (char_length(answer) between 10 and 5000)
);

create table if not exists public.team_members (
  id uuid primary key default gen_random_uuid(),
  display_name text not null,
  role_title text not null,
  bio text not null default '',
  public_email text,
  linkedin_url text,
  media_asset_id uuid references public.media_assets(id) on delete set null,
  status public.content_status not null default 'draft',
  sort_order integer not null default 100,
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  published_at timestamptz,
  archived_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint team_members_name_length check (char_length(display_name) between 2 and 160),
  constraint team_members_role_length check (char_length(role_title) between 2 and 180),
  constraint team_members_bio_length check (char_length(bio) <= 5000)
);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  actor_user_id uuid references auth.users(id) on delete set null,
  action text not null,
  object_type text not null,
  object_id text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint audit_logs_action_length check (char_length(action) between 3 and 160),
  constraint audit_logs_object_type_length check (char_length(object_type) between 2 and 120)
);

create trigger site_settings_set_updated_at
before update on public.site_settings
for each row execute function public.set_updated_at();

create trigger content_sections_set_updated_at
before update on public.content_sections
for each row execute function public.set_updated_at();

create trigger testimonials_set_updated_at
before update on public.testimonials
for each row execute function public.set_updated_at();

create trigger faqs_set_updated_at
before update on public.faqs
for each row execute function public.set_updated_at();

create trigger team_members_set_updated_at
before update on public.team_members
for each row execute function public.set_updated_at();

create index if not exists content_sections_public_idx
  on public.content_sections(status, sort_order)
  where archived_at is null;

create index if not exists testimonials_public_idx
  on public.testimonials(status, permission_granted, sort_order)
  where archived_at is null;

create index if not exists faqs_public_idx
  on public.faqs(status, category, sort_order)
  where archived_at is null;

create index if not exists team_members_public_idx
  on public.team_members(status, sort_order)
  where archived_at is null;

create index if not exists audit_logs_created_idx on public.audit_logs(created_at desc);
create index if not exists audit_logs_actor_created_idx on public.audit_logs(actor_user_id, created_at desc);
create index if not exists audit_logs_object_idx on public.audit_logs(object_type, object_id, created_at desc);

alter table public.site_settings enable row level security;
alter table public.content_sections enable row level security;
alter table public.testimonials enable row level security;
alter table public.faqs enable row level security;
alter table public.team_members enable row level security;
alter table public.audit_logs enable row level security;

grant select on table public.site_settings to anon, authenticated;
grant select on table public.content_sections to anon, authenticated;
grant select on table public.testimonials to anon, authenticated;
grant select on table public.faqs to anon, authenticated;
grant select on table public.team_members to anon, authenticated;
grant select on table public.audit_logs to authenticated;

grant insert, update, delete on table public.content_sections to authenticated;
grant insert, update, delete on table public.testimonials to authenticated;
grant insert, update, delete on table public.faqs to authenticated;
grant insert, update, delete on table public.team_members to authenticated;

grant all on table public.site_settings to service_role;
grant all on table public.content_sections to service_role;
grant all on table public.testimonials to service_role;
grant all on table public.faqs to service_role;
grant all on table public.team_members to service_role;
grant all on table public.audit_logs to service_role;
grant usage, select on sequence public.audit_logs_id_seq to service_role;

drop policy if exists site_settings_public_read_m11 on public.site_settings;
create policy site_settings_public_read_m11
on public.site_settings for select to anon, authenticated
using (is_public = true or public.current_user_is_staff());

drop policy if exists content_sections_public_read_m11 on public.content_sections;
create policy content_sections_public_read_m11
on public.content_sections for select to anon, authenticated
using (
  (status = 'published'::public.content_status and archived_at is null)
  or public.current_user_is_staff()
);

drop policy if exists content_sections_staff_manage_m11 on public.content_sections;
create policy content_sections_staff_manage_m11
on public.content_sections for all to authenticated
using (public.current_user_is_staff())
with check (public.current_user_is_staff());

drop policy if exists testimonials_public_read_m11 on public.testimonials;
create policy testimonials_public_read_m11
on public.testimonials for select to anon, authenticated
using (
  (status = 'published'::public.content_status and permission_granted = true and archived_at is null)
  or public.current_user_is_staff()
);

drop policy if exists testimonials_staff_manage_m11 on public.testimonials;
create policy testimonials_staff_manage_m11
on public.testimonials for all to authenticated
using (public.current_user_is_staff())
with check (public.current_user_is_staff());

drop policy if exists faqs_public_read_m11 on public.faqs;
create policy faqs_public_read_m11
on public.faqs for select to anon, authenticated
using (
  (status = 'published'::public.content_status and archived_at is null)
  or public.current_user_is_staff()
);

drop policy if exists faqs_staff_manage_m11 on public.faqs;
create policy faqs_staff_manage_m11
on public.faqs for all to authenticated
using (public.current_user_is_staff())
with check (public.current_user_is_staff());

drop policy if exists team_members_public_read_m11 on public.team_members;
create policy team_members_public_read_m11
on public.team_members for select to anon, authenticated
using (
  (status = 'published'::public.content_status and archived_at is null)
  or public.current_user_is_staff()
);

drop policy if exists team_members_staff_manage_m11 on public.team_members;
create policy team_members_staff_manage_m11
on public.team_members for all to authenticated
using (public.current_user_is_staff())
with check (public.current_user_is_staff());

drop policy if exists audit_logs_staff_read_m11 on public.audit_logs;
create policy audit_logs_staff_read_m11
on public.audit_logs for select to authenticated
using (public.current_user_is_staff());

