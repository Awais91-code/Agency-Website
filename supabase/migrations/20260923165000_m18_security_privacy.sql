create or replace function public.consume_security_rate_limit(
  p_key_hash text,
  p_bucket text,
  p_limit integer,
  p_window_seconds integer
)
returns table(allowed boolean, remaining integer, reset_at timestamptz)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_window timestamptz;
  v_count integer;
  v_limit integer;
  v_seconds integer;
begin
  v_limit := greatest(1, least(coalesce(p_limit, 1), 10000));
  v_seconds := greatest(10, least(coalesce(p_window_seconds, 60), 86400));

  v_window := to_timestamp(
    floor(extract(epoch from now()) / v_seconds) * v_seconds
  );

  insert into public.security_rate_limits(
    key_hash,
    bucket,
    window_start,
    request_count
  )
  values (
    p_key_hash,
    left(p_bucket, 100),
    v_window,
    1
  )
  on conflict (key_hash, bucket, window_start)
  do update set
    request_count = public.security_rate_limits.request_count + 1,
    updated_at = now()
  returning request_count into v_count;

  delete from public.security_rate_limits
  where updated_at < now() - interval '2 days';

  return query
  select
    v_count <= v_limit,
    greatest(0, v_limit - v_count),
    v_window + make_interval(secs => v_seconds);
end;
$$;

revoke all on function public.consume_security_rate_limit(text, text, integer, integer)
from public, anon, authenticated;

grant execute on function public.consume_security_rate_limit(text, text, integer, integer)
