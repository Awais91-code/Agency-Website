create or replace function public.purge_expired_operational_data()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_security integer := 0;
  v_audit integer := 0;
  v_analytics integer := 0;
  v_booking_webhooks integer := 0;
  v_policy_days integer;
begin
  select retention_days into v_policy_days
  from public.data_retention_policies
  where policy_key = 'security.events' and enabled = true;
  if v_policy_days is not null then
    delete from public.security_events
    where created_at < now() - make_interval(days => v_policy_days);
    get diagnostics v_security = row_count;
  end if;

  select retention_days into v_policy_days
  from public.data_retention_policies
  where policy_key = 'audit.logs' and enabled = true;
  if v_policy_days is not null then
    delete from public.audit_logs
    where created_at < now() - make_interval(days => v_policy_days);
    get diagnostics v_audit = row_count;
  end if;

  select retention_days into v_policy_days
  from public.data_retention_policies
  where policy_key = 'analytics.events' and enabled = true;
  if v_policy_days is not null then
    delete from public.analytics_events
    where created_at < now() - make_interval(days => v_policy_days);
    get diagnostics v_analytics = row_count;
  end if;

  select retention_days into v_policy_days
  from public.data_retention_policies
  where policy_key = 'booking.webhooks' and enabled = true;
  if v_policy_days is not null then
    delete from public.booking_webhook_events
    where processed_at is not null
      and created_at < now() - make_interval(days => v_policy_days);
    get diagnostics v_booking_webhooks = row_count;
  end if;

  return jsonb_build_object(
    'security_events', v_security,
    'audit_logs', v_audit,
    'analytics_events', v_analytics,
    'booking_webhook_events', v_booking_webhooks
  );
end;
$$;

revoke all on function public.purge_expired_operational_data()
from public, anon, authenticated;

grant execute on function public.purge_expired_operational_data()
to service_role;

