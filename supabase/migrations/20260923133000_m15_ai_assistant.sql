create or replace function public.consume_ai_rate_limit(
  p_requester_hash text,
  p_limit integer
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_window timestamptz;
  v_count integer;
begin
  v_window :=
    date_trunc('hour', now())
    + floor(extract(minute from now()) / 10) * interval '10 minutes';

  insert into public.ai_rate_limits(requester_hash, window_start, request_count)
  values (p_requester_hash, v_window, 1)
  on conflict (requester_hash, window_start)
  do update set
    request_count = public.ai_rate_limits.request_count + 1,
    updated_at = now()
  returning request_count into v_count;

  delete from public.ai_rate_limits
  where window_start < now() - interval '2 days';

  return v_count <= greatest(1, p_limit);
end;
$$;

revoke all on function public.consume_ai_rate_limit(text, integer) from public, anon, authenticated;
grant execute on function public.consume_ai_rate_limit(text, integer) to service_role;

create or replace function public.purge_expired_ai_conversations()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_deleted integer;
begin
  delete from public.ai_conversations
  where retain_until < now();

  get diagnostics v_deleted = row_count;

  delete from public.ai_events
  where conversation_id is null
    and created_at < now() - interval '90 days';

  return v_deleted;
end;
$$;

revoke all on function public.purge_expired_ai_conversations() from public, anon, authenticated;
grant execute on function public.purge_expired_ai_conversations() to service_role;

