create table if not exists public.ai_settings (
  id text primary key default 'default',
  assistant_enabled boolean not null default true,
  provider text not null default 'openai',
  model text not null default 'gpt-5.6-luna',
  prompt_version text not null default 'm15-v1',
  logging_enabled boolean not null default true,
  review_enabled boolean not null default true,
  retention_days integer not null default 30,
  max_messages_per_conversation integer not null default 20,
  rate_limit_per_10m integer not null default 12,
  handoff_label text not null default 'Talk to a human',
  handoff_href text not null default '/contact',
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint ai_settings_singleton check (id = 'default'),
  constraint ai_settings_retention check (retention_days between 1 and 365),
  constraint ai_settings_message_limit check (max_messages_per_conversation between 3 and 100),
  constraint ai_settings_rate_limit check (rate_limit_per_10m between 1 and 200)
